#nullable enable
// Copilot protocol-3 frames (spec §9, plan §2.2; owned by W0, contracts).
// Revit-free mirror of contracts/copilot/protocol3.schema.json: request bodies
// the add-in POSTs, and the data of each SSE event the cloud streams back.
//
// SSE wire format: "event: <type>\ndata: <json>\n\n". Every event's data
// carries seq (starts at 1, increases within a turn). A stream ends after
// tool_request, ask or turn_end; POST .../results opens the next one.

using System.Collections.Generic;
using System.Text.Json;
using System.Text.Json.Serialization;

namespace BinaVibe.Copilot.Contracts
{
    public static class Protocol
    {
        public const int Version = 3;
        public const string TurnsPath = "/copilot/turns";

        public static string ResultsPath(string turnId) => TurnsPath + "/" + turnId + "/results";
        public static string EventsPath(string turnId, long afterSeq) => TurnsPath + "/" + turnId + "/events?after=" + afterSeq;
        public static string CancelPath(string turnId) => TurnsPath + "/" + turnId + "/cancel";
    }

    public static class SseEventTypes
    {
        public const string Progress = "progress";
        public const string ReplyDelta = "reply_delta";
        public const string ToolRequest = "tool_request";
        public const string Ask = "ask";
        public const string TurnEnd = "turn_end";
        public const string Error = "error";

        public static IReadOnlyList<string> All { get; } = new[] { Progress, ReplyDelta, ToolRequest, Ask, TurnEnd, Error };
    }

    public static class ProgressKinds
    {
        public const string Thinking = "thinking";
        public const string Running = "running";
        public const string AwaitingConfirm = "awaiting_confirm";
        public const string RevitBusy = "revit_busy";

        public static IReadOnlyList<string> All { get; } = new[] { Thinking, Running, AwaitingConfirm, RevitBusy };
    }

    public static class ToolRequestKinds
    {
        public const string Read = "read";
        public const string Write = "write";

        public static IReadOnlyList<string> All { get; } = new[] { Read, Write };
    }

    public static class TurnEndStatus
    {
        public const string Done = "done";
        public const string Cancelled = "cancelled";
        public const string Failed = "failed";
        public const string Limit = "limit";
        public const string Interrupted = "interrupted";

        public static IReadOnlyList<string> All { get; } = new[] { Done, Cancelled, Failed, Limit, Interrupted };
    }

    public static class AskPurposes
    {
        public const string Clarify = "clarify";
        public const string ProjectNote = "project_note";

        public static IReadOnlyList<string> All { get; } = new[] { Clarify, ProjectNote };
    }

    public static class AskFieldTypes
    {
        public const string Text = "text";
        public const string Number = "number";
        /// <summary>Needs <see cref="AskFieldDto.Choices"/>.</summary>
        public const string Choice = "choice";

        public static IReadOnlyList<string> All { get; } = new[] { Text, Number, Choice };
    }

    public static class AttachmentKinds
    {
        public const string Table = "table";
        public const string Image = "image";
        /// <summary>Needs <see cref="AttachmentDto.Pages"/>.</summary>
        public const string Document = "document";

        public static IReadOnlyList<string> All { get; } = new[] { Table, Image, Document };
    }

    // ------------------------------------------------------------------
    // Requests (add-in -> cloud)
    // ------------------------------------------------------------------

    /// <summary>Body of POST /copilot/turns. 409 when a turn is already active
    /// for the session; 426 (<see cref="UpdateRequiredDto"/>) on a protocol mismatch.</summary>
    public sealed class TurnRequestDto
    {
        [JsonPropertyName("protocol")] public int Protocol { get; set; } = Contracts.Protocol.Version;
        /// <summary>UUID generated by the add-in.</summary>
        [JsonPropertyName("turn_id")] public string TurnId { get; set; } = "";
        /// <summary>From the previous turn_end; null starts a new session.</summary>
        [JsonPropertyName("session_id")] public string? SessionId { get; set; }
        [JsonPropertyName("text")] public string Text { get; set; } = "";
        /// <summary>"en" or "ms": the prompt language, detected once by the add-in; the reply follows it.</summary>
        [JsonPropertyName("lang")] public string? Lang { get; set; }
        [JsonPropertyName("snapshot")] public SnapshotModel Snapshot { get; set; } = new();
        [JsonPropertyName("attachments")] public List<AttachmentDto> Attachments { get; set; } = new();
    }

    public sealed class AttachmentDto
    {
        [JsonPropertyName("name")] public string Name { get; set; } = "";
        /// <summary>One of <see cref="AttachmentKinds"/>.</summary>
        [JsonPropertyName("kind")] public string Kind { get; set; } = "";
        /// <summary>Required for tables.</summary>
        [JsonPropertyName("columns")] public List<string>? Columns { get; set; }
        /// <summary>Required for tables: row-major cells (string, number, bool or null), one per column.</summary>
        [JsonPropertyName("rows")] public List<List<JsonElement>>? Rows { get; set; }
        /// <summary>Required for images.</summary>
        [JsonPropertyName("image_b64")] public string? ImageB64 { get; set; }
        /// <summary>Required for documents: the pages in order. The cloud shows them to the model on this turn only.</summary>
        [JsonPropertyName("pages")] public List<AttachmentPageDto>? Pages { get; set; }
        /// <summary>Pages in the file; more than Pages.Count when the add-in cut the document.</summary>
        [JsonPropertyName("page_count")] public int? PageCount { get; set; }
    }

    /// <summary>One page of a document attachment; Text is empty for a page without a text layer.</summary>
    public sealed class AttachmentPageDto
    {
        /// <summary>1-based page number in the file.</summary>
        [JsonPropertyName("page")] public int Page { get; set; }
        /// <summary>Always set when sending; null only when a peer's page had no text key (a contract break).</summary>
        [JsonPropertyName("text")] public string? Text { get; set; }
    }

    /// <summary>Body of POST /copilot/turns/{turn_id}/results: either Results (for a
    /// tool_request) or Answer (for an ask), never both. Idempotent by RequestId.</summary>
    public sealed class ResultsRequestDto
    {
        [JsonPropertyName("protocol")] public int Protocol { get; set; } = Contracts.Protocol.Version;
        [JsonPropertyName("request_id")] public string RequestId { get; set; } = "";
        /// <summary>One per call of the tool_request, in call order.</summary>
        [JsonPropertyName("results")] public List<ToolResultDto>? Results { get; set; }
        [JsonPropertyName("answer")] public AnswerDto? Answer { get; set; }
        [JsonPropertyName("snapshot")] public SnapshotModel Snapshot { get; set; } = new();
    }

    public sealed class ToolResultDto
    {
        [JsonPropertyName("call_id")] public string CallId { get; set; } = "";
        [JsonPropertyName("envelope")] public Envelope Envelope { get; set; } = new();
    }

    public sealed class AnswerDto
    {
        /// <summary>Keyed by field id or option id: a chosen option is "&lt;option_id&gt;": true;
        /// a question with neither options nor fields is answered under "text".
        /// Values are JSON strings, numbers or booleans.</summary>
        [JsonPropertyName("values")] public Dictionary<string, JsonElement> Values { get; set; } = new();
    }

    /// <summary>Body of a 426 response.</summary>
    public sealed class UpdateRequiredDto
    {
        [JsonPropertyName("update_required")] public bool UpdateRequired { get; set; } = true;
    }

    // ------------------------------------------------------------------
    // SSE event data (cloud -> add-in)
    // ------------------------------------------------------------------

    public abstract class SseEventData
    {
        [JsonPropertyName("seq")] public long Seq { get; set; }
    }

    public sealed class ProgressDto : SseEventData
    {
        /// <summary>One of <see cref="ProgressKinds"/>.</summary>
        [JsonPropertyName("kind")] public string Kind { get; set; } = "";
        [JsonPropertyName("text")] public string Text { get; set; } = "";
        /// <summary>The model step (1, 2, ...) the frame belongs to; there is no total. Absent from an older server.</summary>
        [JsonPropertyName("step")] public int? Step { get; set; }
    }

    public sealed class ReplyDeltaDto : SseEventData
    {
        [JsonPropertyName("text")] public string Text { get; set; } = "";
    }

    /// <summary>Calls for the add-in to run. Read requests never carry set_parameters;
    /// write requests carry only set_parameters and run_revit_code.</summary>
    public sealed class ToolRequestDto : SseEventData
    {
        [JsonPropertyName("request_id")] public string RequestId { get; set; } = "";
        /// <summary>One of <see cref="ToolRequestKinds"/>.</summary>
        [JsonPropertyName("kind")] public string Kind { get; set; } = "";
        [JsonPropertyName("calls")] public List<ToolCallDto> Calls { get; set; } = new();
        /// <summary>The assistant's words about the batch, shown on a labelled line of the result card.</summary>
        [JsonPropertyName("description")] public string? Description { get; set; }
    }

    public sealed class ToolCallDto
    {
        [JsonPropertyName("call_id")] public string CallId { get; set; } = "";
        /// <summary>Stable across retries of the same call; the ledger keys commits on it.</summary>
        [JsonPropertyName("idempotency_key")] public string IdempotencyKey { get; set; } = "";
        /// <summary>One of <see cref="ToolNames.AddIn"/>.</summary>
        [JsonPropertyName("tool")] public string Tool { get; set; } = "";
        /// <summary>The model's arguments after the cloud-side rewrites (check gets
        /// rule_set_content, set_parameters gets table_rows).</summary>
        [JsonPropertyName("args")] public JsonElement Args { get; set; }
    }

    /// <summary>A question for the drafter (from ask_user). With neither options nor
    /// fields, the pane shows one free-text box answered under the id "text".</summary>
    public sealed class AskDto : SseEventData
    {
        [JsonPropertyName("request_id")] public string RequestId { get; set; } = "";
        [JsonPropertyName("question")] public string Question { get; set; } = "";
        /// <summary>2–4 options.</summary>
        [JsonPropertyName("options")] public List<AskOptionDto>? Options { get; set; }
        [JsonPropertyName("fields")] public List<AskFieldDto>? Fields { get; set; }
        [JsonPropertyName("multi")] public bool Multi { get; set; }
        /// <summary>One of <see cref="AskPurposes"/>.</summary>
        [JsonPropertyName("purpose")] public string Purpose { get; set; } = AskPurposes.Clarify;
        /// <summary>The project fact to save; required when Purpose is project_note.</summary>
        [JsonPropertyName("note_text")] public string? NoteText { get; set; }
        // Optional decision-card additions (card spec, "The frame"). A question the model asks itself
        // has none of them; the card still draws.
        /// <summary>The card's heading, e.g. "Before I make the sheets".</summary>
        [JsonPropertyName("title")] public string? Title { get; set; }
        /// <summary>What one made thing is called, singular, lower case ("sheet"): the button says "Make 5 sheets".</summary>
        [JsonPropertyName("noun")] public string? Noun { get; set; }
        /// <summary>Things that need no decision and will be made.</summary>
        [JsonPropertyName("ready")] public List<AskReadyDto>? Ready { get; set; }
    }

    /// <summary>One thing the card lists as ready (needs no decision).</summary>
    public sealed class AskReadyDto
    {
        [JsonPropertyName("label")] public string Label { get; set; } = "";
        [JsonPropertyName("detail")] public string? Detail { get; set; }
    }

    /// <summary>What picking an option does (ask_option.kind); absent means an ordinary pick.</summary>
    public static class AskOptionKinds
    {
        public const string Create = "create";
        public const string Skip = "skip";

        public static IReadOnlyList<string> All { get; } = new[] { Create, Skip };
    }

    public sealed class AskOptionDto
    {
        [JsonPropertyName("id")] public string Id { get; set; } = "";
        [JsonPropertyName("label")] public string Label { get; set; } = "";
        /// <summary>Small secondary text, e.g. a scale "1:200".</summary>
        [JsonPropertyName("meta")] public string? Meta { get; set; }
        /// <summary>One of <see cref="AskOptionKinds"/>, or null for an ordinary pick.</summary>
        [JsonPropertyName("kind")] public string? Kind { get; set; }
    }

    public sealed class AskFieldDto
    {
        [JsonPropertyName("id")] public string Id { get; set; } = "";
        [JsonPropertyName("label")] public string Label { get; set; } = "";
        /// <summary>One of <see cref="AskFieldTypes"/>.</summary>
        [JsonPropertyName("type")] public string Type { get; set; } = "";
        [JsonPropertyName("unit")] public string? Unit { get; set; }
        /// <summary>At least 2; required when Type is choice. The answer value is the chosen id.</summary>
        [JsonPropertyName("choices")] public List<AskOptionDto>? Choices { get; set; }
        /// <summary>The heading the field is listed under, e.g. "No floor plan".</summary>
        [JsonPropertyName("group")] public string? Group { get; set; }
        /// <summary>A short fact shown after the label, e.g. "2 floor plans".</summary>
        [JsonPropertyName("note")] public string? Note { get; set; }
    }

    public sealed class TurnEndDto : SseEventData
    {
        /// <summary>One of <see cref="TurnEndStatus"/>.</summary>
        [JsonPropertyName("status")] public string Status { get; set; } = "";
        [JsonPropertyName("session_id")] public string SessionId { get; set; } = "";
        [JsonPropertyName("receipt_ids")] public List<string> ReceiptIds { get; set; } = new();
        /// <summary>The turn's typed result as the server sent it. Optional: an old server never
        /// sends it. Kept as raw JSON so a result this add-in cannot read never loses the turn_end;
        /// use <see cref="ReadResult"/>.</summary>
        [JsonPropertyName("result")] public JsonElement? Result { get; set; }

        /// <summary>The typed result, or null when the turn_end has none or it is unreadable:
        /// the pane then shows the streamed prose.</summary>
        public TurnResultDto? ReadResult() => TurnResultReader.TryRead(Result);
    }

    /// <summary>The SSE <c>error</c> event (not the envelope's <see cref="ErrorDto"/>).</summary>
    public sealed class StreamErrorDto : SseEventData
    {
        [JsonPropertyName("code")] public string Code { get; set; } = "";
        [JsonPropertyName("message")] public string Message { get; set; } = "";
    }
}
